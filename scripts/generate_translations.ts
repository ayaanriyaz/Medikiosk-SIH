// Regional generator function
function generateRegionalLanguage(
  langCode: string,
  overrides: Record<string, string>
): Record<string, any> {
  const result: Record<string, any> = {};
  for (const key of Object.keys(completeEn)) {
    if (key === 'stepOf') {
      result[key] = (step: number, total: number) => `${step} / ${total}`;
    } else if (overrides[key]) {
      result[key] = overrides[key];
    } else if (completeHi[key]) {
      result[key] = completeHi[key];
    } else {
      result[key] = completeEn[key];
    }
  }
  return result;
}

function serializeLangFile(langCode: string, dict: Record<string, any>): string {
  let content = `import { TranslationStrings } from '../translations';\n\nexport const ${langCode}: TranslationStrings = {\n`;
  for (const [key, value] of Object.entries(dict)) {
    if (typeof value === 'function' || key === 'stepOf') {
      content += `  ${key}: (step: number, total: number) => \`Step \${step} of \${total}\`,\n`;
    } else if (typeof value === 'string') {
      const escaped = value.replace(/\\/g, '\\\\').replace(/'/g, "\\'").replace(/\n/g, '\\n');
      content += `  ${key}: '${escaped}',\n`;
    } else {
      content += `  ${key}: ${JSON.stringify(value)},\n`;
    }
  }
  content += `};\n`;
  return content;
}

// Write files
const outputDir = path.join(process.cwd(), 'src/i18n/translations');
fs.mkdirSync(outputDir, { recursive: true });

fs.writeFileSync(path.join(outputDir, 'en.ts'), serializeLangFile('en', completeEn));
fs.writeFileSync(path.join(outputDir, 'hi.ts'), serializeLangFile('hi', completeHi));
fs.writeFileSync(path.join(outputDir, 'mr.ts'), serializeLangFile('mr', completeMr));

for (const [code, overrides] of Object.entries(REGIONAL_TRANSLATIONS)) {
  const regionalDict = generateRegionalLanguage(code, overrides);
  fs.writeFileSync(path.join(outputDir, `${code}.ts`), serializeLangFile(code, regionalDict));
}

