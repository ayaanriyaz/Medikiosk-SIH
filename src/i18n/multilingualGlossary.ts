/**
 * Universal phrase localizer
 * Translates standard medical/clinical English strings into the current target language
 */
export function getLocalizedPhrase(englishText: string, targetLang: string): string {
  if (!englishText || targetLang === 'en') return englishText;

  const glossary = MULTILINGUAL_GLOSSARY[targetLang];
  if (!glossary) return englishText;

  // Exact key lookup in glossary
  for (const [key, val] of Object.entries(glossary)) {
    if (val && key.toLowerCase() === englishText.toLowerCase().replace(/[^a-z0-9]/g, '')) {
      return val;
    }
  }

  // Common phrase mappings
  const normalized = englishText.trim().toLowerCase();

  const phraseMap: Record<string, string> = {
    'live waiting queue': glossary.liveQueueTitle,
    'opd waiting queue': glossary.liveQueueTitle,
    'essential medicines': glossary.medicineStockTitle,
    'medicine stock': glossary.medicineStockTitle,
    'emergency referrals': glossary.referralTitle,
    'referrals & ambulance': glossary.referralTitle,
    'high-risk follow-up': glossary.highRiskFollowupTitle,
    'asha worker hub': glossary.ashaHubTitle,
    'district health dashboard': glossary.districtDashboardTitle,
    'diagnostics & lab': glossary.diagnosticsTitle,
    'patient identification': glossary.kioskStartIntakeBtn,
    'print opd token': glossary.kioskPrintTokenBtn,
    'start patient intake': glossary.kioskStartIntakeBtn,
    'enter medikiosk': glossary.patientModeNav,
    'doctor workspace': glossary.doctorWorkspaceNav,
    'hospital login': glossary.hospitalOpsNav,
    'doctor login': glossary.doctorWorkspaceNav,
    'estimated wait': glossary.estimatedWait,
    'room number': glossary.roomNumber,
    'token number': glossary.tokenNumber,
    'assigned doctor': glossary.assignedDoctor,
    'continue': glossary.continue,
    'back': glossary.back,
    'next': glossary.next,
    'submit': glossary.submit,
    'agree': glossary.agree,
    'disagree': glossary.disagree,
  };

  if (phraseMap[normalized]) {
    return phraseMap[normalized];
  }

  return englishText;
}
